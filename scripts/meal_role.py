def _clean(name):
    s = re.sub(r"\[[^\]]*\]|\([^)]*\)|<[^>]*>", " ", name or "")
    s = re.sub(r"\d+(\.\d+)?\s*(g|kg|ml|mL|l|L|개입|입|개|팩|봉|매|ea|EA|인분|p|P|cm)\b", " ", s)
    s = re.sub(r"[xX×*]\s*\d+", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def meal_role(p, food_type=""):
    name = _clean(p.get("name") or "")
    cat = p.get("dish_category") or "other"
    ft = food_type or p.get("food_type") or ""

    if "건강기능" in ft or cat == "supplement" or SUPPLEMENT.search(name): return "supplement"
    if CONDIMENT.search(name) or re.search(r"페스토|스프레드|파스타\s?디\s|크레마\s?디|(소스|양념장|양념)\s?\S*맛$", name) or (cat == "sauce" and not MEAL.search(name)): return "condiment"
    if BROTH.search(name): return "ingredient"
    if re.search(r"미숫가루|선식|쉐이크|셰이크|프로틴\s?파우더|단백질\s?파우더", name): return "drink"
    if RAW_MARK.search(name): return "ingredient"
    if cat == "beverage": return "drink"
    if RAW_TAIL.search(name) and not COOKED.search(name): return "ingredient"
    # 이름은 '떡볶이'인데 나트륨이 거의 없는 것 — 양념 없는 떡볶이 떡
    sod = p.get("sodium_mg")
    if re.search(r"떡볶이", name) and sod is not None and float(sod) < 150 and not re.search(r"소스|양념|맛$", name): return "ingredient"
    if cat == "powder": return "drink"
    if PASTA_RAW.search(name) and not PASTA_DISH.search(name): return "ingredient"
    strong_meal = re.search(r"도시락(?!\s?김)|식단|정식|볶음밥|덮밥|비빔밥|국밥|밀키트", name)
    if SNACK.search(name) and not strong_meal: return "snack"
    if DRINK.search(name) and not MEAL.search(name): return "drink"
    if re.search(r"소시지|비엔나|후랑크|프랑크|햄$|런천|텐더|너겟|김$|곱창김|김\s?캔|김자반", name) and not strong_meal: return "side"
    if cat == "ingredient": return "ingredient"
    bare = re.sub(r"\s+", "", name)
    if PLAIN_RICE.search(bare): return "side"
    kcal = p.get("calories")
    # 물에 풀어 먹는 분말 수프·고형 카레(100g 당 300kcal 넘는 것) — 조리 재료
    if kcal is not None and float(kcal) >= 300 and re.search(r"스프$|수프$|카레|커리|후레이크|짜장\s?분말|하이라이스", name) \
            and not re.search(r"덮밥|라이스|볶음밥|도시락|면$|라면|우동|팝콘|과자|칩", name):
        return "ingredient"  # 밥만 — 반찬과 같이 먹는 것
    # '떡볶이맛'·'불고기맛'처럼 요리 이름이 맛 이름으로만 붙은 과자 — 맛 이름을 떼면 한 끼 말이 없다
    if MEAL.search(name) and name.endswith("맛") and not MEAL.search(re.sub(r"\S*맛$", "", name)) and not strong_meal:
        return "snack"
