export const MILESTONES = [3, 7, 14, 30, 50, 100, 200, 365];

export type LineCtx = { food?: string | null; days: number; seed: number };

/** 문장 하나 — 같은 날·같은 상황이면 같은 문장 (seed) */
export function buddyLine(ingredient: string, personality: string, situation: Situation, ctx: LineCtx) {
  const ing = ingredientOf(ingredient);
  const per = personalityOf(personality);
  if (!ing || !per) return "";
  const pair = BANK[per.key][situation];
  const s = seedOf(ctx.seed, situation);
  const text = pair[s % pair.length];
  const food = (ctx.food || "").trim().slice(0, 16) || "이번 끼니";
  return text
    .replaceAll("{food}", food)
    .replaceAll("{days}", String(Math.max(1, ctx.days)))
    .replaceAll("{me}", ing.name)
    .replaceAll("{name}", `${per.adj} ${ing.name}`)
    .replaceAll("{word}", ing.words[s % 2]);
}

/** 지금 무슨 말을 할 상황인가 — 표정(lib/mascot.ts moodOf)에서. 오늘 처음 만났으면 인사, 돌아왔으면 반가워하기, 이어 간 날 마디면 축하 */
export function situationOf(o: { mood: MascotMood; welcomeBack: boolean; todayRecords: number; streak: number; hatchedToday: boolean }): Situation {
  if (o.hatchedToday && o.todayRecords === 0) return "hello";
  if (o.welcomeBack) return "back";
  if (o.mood === "logged") return MILESTONES.includes(o.streak) ? "milestone" : "logged";
  return o.mood;
}
